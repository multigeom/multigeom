"""
The denoised image of a diffusion model: Tweedie's posterior mean
x̂(x_t) = (x_t − √(1 − ᾱ_t) ε̂(x_t)) / √ᾱ_t, from the noise ε̂ predicted at the DDPM step
t, without responses (the null token: the unconditional model) or given responses; and
images generated from pure noise with the DDPM sampler.
"""

from __future__ import annotations

from collections.abc import Sequence

import torch


def compute_denoised(
    unet: torch.nn.Module,
    x_t: torch.Tensor,
    t_j: int,
    alphas_cumprod: torch.Tensor,
    responses: torch.Tensor | None = None,
    clamp: bool = False,
) -> tuple[torch.Tensor, torch.Tensor]:
    """
    The denoised images x̂(x_t) of the noisy images `x_t` [B, C, H, W] at the DDPM step
    `t_j`, from `unet(x_t, t, r)` (with `n_neurons`): with the null token (zero
    responses, the unconditional model) if `responses` is None, else given `responses`
    [B, n_neurons]. `clamp` clips x̂ to [-1, 1], the range of the canonical images;
    leave it off for images that are not bounded to it, such as whitened ones.

    Returns:
        x̂ [B, C, H, W], and the predicted noise ε̂ [B, C, H, W] it comes from.
    """
    sqrt_ab = float(alphas_cumprod[t_j].sqrt())
    sqrt_1m = float((1.0 - alphas_cumprod[t_j]).sqrt())
    steps = torch.full((len(x_t),), t_j, device=x_t.device, dtype=torch.long)
    if responses is None:
        responses = torch.zeros(len(x_t), unet.n_neurons, device=x_t.device)
    eps = unet(x_t, steps, responses)
    x_hat = (x_t - sqrt_1m * eps) / sqrt_ab
    return (x_hat.clamp(-1.0, 1.0) if clamp else x_hat), eps


@torch.no_grad()
def sample_images(
    unet: torch.nn.Module,
    alphas_cumprod: torch.Tensor,
    shape: tuple[int, ...],
    device: torch.device,
    generator: torch.Generator | None = None,
    batch_size: int = 64,
    keep: Sequence[int] = (),
    responses: torch.Tensor | None = None,
) -> torch.Tensor | tuple[torch.Tensor, dict]:
    """
    Images [n, C, H, W] (`shape`) generated by a diffusion model from pure noise, with
    the null token of `unet` (the unconditional model) and the DDPM sampler it was
    trained for: from the last step to the first, each step replaces x_t by the mean of
    x_{t−1} given x_t and the predicted noise, plus fresh noise of the posterior
    variance β_t (1 − ᾱ_{t−1}) / (1 − ᾱ_t) (none at the last step). Not clipped, so
    that images not bounded to [-1, 1], such as whitened ones, keep their range.
    `generator` (on `device`) seeds the noise; `batch_size` images go at once.

    With `keep` (DDPM steps), also returns the trajectory: {step: (x_t, x̂(x_t))}, the
    noisy images at that step and the denoised images predicted from them by Tweedie's
    formula, each [n, C, H, W] on the CPU, in the order of the generation (coarsest
    first). Keeping them does not change the samples.

    With `responses` [n, n_neurons] (in the units the model was conditioned on), image
    i is generated given responses[i] instead of the null token: a sample of p(x | r),
    and its x̂(x_t, r) along the trajectory.
    """
    alphas_cumprod = alphas_cumprod.to(device)
    batches, kept = [], {t_j: ([], []) for t_j in sorted(keep, reverse=True)}
    for start in range(0, shape[0], batch_size):
        # pure noise, at the last step
        size = (min(batch_size, shape[0] - start), *shape[1:])
        x = torch.randn(size, device=device, generator=generator)
        if responses is None:
            condition = torch.zeros(size[0], unet.n_neurons, device=device)
        else:
            condition = responses[start : start + size[0]].to(device, x.dtype)

        # one DDPM step at a time, back to the first
        for t_j in range(len(alphas_cumprod) - 1, -1, -1):
            ab = alphas_cumprod[t_j]
            ab_prev = alphas_cumprod[t_j - 1] if t_j > 0 else torch.ones_like(ab)
            beta = 1.0 - ab / ab_prev
            steps = torch.full((size[0],), t_j, device=device, dtype=torch.long)
            eps = unet(x, steps, condition)
            if t_j in kept:
                kept[t_j][0].append(x.cpu())
                kept[t_j][1].append(((x - (1.0 - ab).sqrt() * eps) / ab.sqrt()).cpu())
            x = (x - beta / (1.0 - ab).sqrt() * eps) / (1.0 - beta).sqrt()
            if t_j > 0:
                variance = beta * (1.0 - ab_prev) / (1.0 - ab)
                noise = torch.randn(size, device=device, generator=generator)
                x = x + variance.sqrt() * noise
        batches.append(x)
    images = torch.cat(batches)
    if not keep:
        return images
    trajectory = {t_j: (torch.cat(a), torch.cat(b)) for t_j, (a, b) in kept.items()}
    return images, trajectory
